#!/usr/bin/env python3
"""Draw the port's own button glyphs (Switch and PlayStation style) and write
them as src/clx_glyphs.h, ARGB pixels (0xAARRGGBB) at the sizes of the title's
Xbox icon textures they replace: 32x32 face buttons, 64x64 triggers and stick.

Our own drawings (shapes plus DejaVu Sans Bold letters, Bitstream Vera
licence), not Nintendo's or Sony's artwork.

    python3 tools/make_glyphs.py            # needs Pillow and a DejaVu font
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = ['/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',
         'C:/Windows/Fonts/DejaVuSans-Bold.ttf', 'C:/Windows/Fonts/arialbd.ttf']
SS = 8                                       # supersampling


def font(px):
    for f in FONTS:
        if os.path.exists(f):
            return ImageFont.truetype(f, px)
    sys.exit('no DejaVu Sans Bold font found')


def canvas(n):
    im = Image.new('RGBA', (n * SS, n * SS), (0, 0, 0, 0))
    return im, ImageDraw.Draw(im)


def text_center(dr, n, s, size, fill):
    f = font(int(size * SS))
    x0, y0, x1, y1 = dr.textbbox((0, 0), s, font=f)
    dr.text(((n * SS - (x1 - x0)) / 2 - x0, (n * SS - (y1 - y0)) / 2 - y0), s, font=f, fill=fill)


def face_switch(letter, n=32):
    """Flat light round button, thin grey rim, black letter."""
    im, dr = canvas(n)
    m = SS
    dr.ellipse((m, m, n * SS - m, n * SS - m), fill=(120, 120, 128, 255))
    dr.ellipse((m + 2 * SS, m + 2 * SS, n * SS - m - 2 * SS, n * SS - m - 2 * SS), fill=(236, 236, 240, 255))
    text_center(dr, n, letter, n * 0.56, (20, 20, 24, 255))
    return im.resize((n, n), Image.LANCZOS)


def face_ps(symbol, n=32):
    """Dark round button with a coloured PlayStation-style symbol."""
    im, dr = canvas(n)
    m, S = SS, n * SS
    dr.ellipse((m, m, S - m, S - m), fill=(40, 40, 46, 255))
    w = int(S * 0.08)
    a, b = S * 0.32, S * 0.68
    if symbol == 'cross':
        c = (120, 170, 255, 255)
        dr.line((a, a, b, b), fill=c, width=w)
        dr.line((a, b, b, a), fill=c, width=w)
    elif symbol == 'circle':
        dr.ellipse((a, a, b, b), outline=(255, 100, 110, 255), width=w)
    elif symbol == 'square':
        dr.rectangle((a, a, b, b), outline=(240, 140, 220, 255), width=w)
    else:                                    # triangle
        c = (90, 220, 180, 255)
        pts = [(S / 2, S * 0.28), (S * 0.72, S * 0.68), (S * 0.28, S * 0.68)]
        dr.line(pts + [pts[0]], fill=c, width=w, joint='curve')
    return im.resize((n, n), Image.LANCZOS)


def shoulder(label, light, n=64):
    """A shoulder/trigger button seen from the front, with its name."""
    im, dr = canvas(n)
    S = n * SS
    body, rim, ink = ((236, 236, 240, 255), (120, 120, 128, 255), (20, 20, 24, 255)) if light \
        else ((40, 40, 46, 255), (90, 90, 100, 255), (235, 235, 240, 255))
    box = (S * 0.12, S * 0.22, S * 0.88, S * 0.78)
    dr.rounded_rectangle(box, radius=S * 0.18, fill=rim)
    i = S * 0.035
    dr.rounded_rectangle((box[0] + i, box[1] + i, box[2] - i, box[3] - i), radius=S * 0.15, fill=body)
    text_center(dr, n, label, n * 0.36, ink)
    return im.resize((n, n), Image.LANCZOS)


def stick(n=64):
    """A thumbstick from above: dark cap, lighter rim, concave centre."""
    im, dr = canvas(n)
    S = n * SS
    dr.ellipse((S * 0.08, S * 0.08, S * 0.92, S * 0.92), fill=(70, 70, 78, 255))
    dr.ellipse((S * 0.14, S * 0.14, S * 0.86, S * 0.86), fill=(150, 150, 160, 255))
    dr.ellipse((S * 0.26, S * 0.26, S * 0.74, S * 0.74), fill=(110, 110, 120, 255))
    dr.ellipse((S * 0.34, S * 0.34, S * 0.66, S * 0.66), fill=(95, 95, 104, 255))
    return im.resize((n, n), Image.LANCZOS)


GLYPHS = [
    ('SW_A', face_switch('A')), ('SW_B', face_switch('B')),
    ('SW_X', face_switch('X')), ('SW_Y', face_switch('Y')),
    ('SW_ZL', shoulder('ZL', True)), ('SW_ZR', shoulder('ZR', True)),
    ('PS_CROSS', face_ps('cross')), ('PS_CIRCLE', face_ps('circle')),
    ('PS_SQUARE', face_ps('square')), ('PS_TRIANGLE', face_ps('triangle')),
    ('PS_L2', shoulder('L2', False)), ('PS_R2', shoulder('R2', False)),
    ('STICK', stick()),
]


def main():
    out = os.path.join(ROOT, 'src', 'clx_glyphs.h')
    prev = os.path.join(ROOT, 'docs', 'glyphs_preview.png')
    with open(out, 'w', newline='\n') as f:
        f.write('/* Generated by tools/make_glyphs.py: the port\'s own button glyphs, ARGB. Do not edit. */\n')
        f.write('#ifndef CLX_GLYPHS_H\n#define CLX_GLYPHS_H\n#include <stdint.h>\n\n')
        f.write('enum {\n' + ''.join('    G_%s,\n' % n for n, _ in GLYPHS) + '    G_COUNT\n};\n\n')
        for name, im in GLYPHS:
            px = list(im.getdata())
            f.write('static const uint32_t k_glyph_%s[%d] = {\n' % (name.lower(), len(px)))
            for k in range(0, len(px), 8):
                f.write('    ' + ', '.join('0x%02X%02X%02X%02Xu' % (a, r, g, b) for r, g, b, a in px[k:k + 8]) + ',\n')
            f.write('};\n')
        f.write('\nstatic const struct { const uint32_t *px; uint32_t size; } k_glyphs[G_COUNT] = {\n')
        for name, im in GLYPHS:
            f.write('    { k_glyph_%s, %d },\n' % (name.lower(), im.size[0]))
        f.write('};\n\n#endif\n')
    sheet = Image.new('RGBA', (len(GLYPHS) * 72, 72), (96, 96, 96, 255))
    for k, (_, im) in enumerate(GLYPHS):
        sheet.alpha_composite(im.resize((64, 64), Image.NEAREST) if im.size[0] == 32 else im, (k * 72 + 4, 4))
    sheet.save(prev)
    print(out, prev)


if __name__ == '__main__':
    main()
