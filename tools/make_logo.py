#!/usr/bin/env python3
"""Make the Switch art from the XBE's own dashboard title image ($$XTIMAGE:
an XPR0 file, DXT1 128x128, data after its 0x800-byte header):

  assets/icon.jpg   256x256 homebrew icon (nx_create_nro)
  src/logo.h        the loading screen's logo (switch_nx.c), run-length
                    encoded as (count, R, G, B); the loader blits it, so it
                    is composited onto the loader's background first.

    python3 tools/make_logo.py path/to/default.xbe     # needs Pillow
"""
import os, struct, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SIZE = 256
BG = (8, 10, 13)          # switch_nx.c: loader background


def title_image(xbe):
    d = open(xbe, "rb").read()
    base = struct.unpack_from("<I", d, 0x104)[0]
    nsec, shdr = struct.unpack_from("<II", d, 0x11C)
    for i in range(nsec):
        _, _, _, raw, rsz, name = struct.unpack_from("<6I", d, shdr - base + i * 0x38)
        if d[name - base:name - base + 10] == b"$$XTIMAGE\0":
            xpr = d[raw:raw + rsz]
            assert xpr[:4] == b"XPR0", "title image is not an XPR0 file"
            hdr = struct.unpack_from("<I", xpr, 8)[0]
            fmt = struct.unpack_from("<I", xpr, 0x18)[0]
            assert (fmt >> 8) & 0xFF == 0x0C, "title image is not DXT1"
            w, h = 1 << ((fmt >> 20) & 15), 1 << ((fmt >> 24) & 15)
            return Image.frombytes("RGBA", (w, h), xpr[hdr:hdr + w * h // 2], "bcn", 1)
    sys.exit("no $$XTIMAGE section")


im = title_image(sys.argv[1]).resize((SIZE, SIZE), Image.LANCZOS)
os.makedirs(os.path.join(ROOT, "assets"), exist_ok=True)   # not in git: a fresh clone has none
im.convert("RGB").save(os.path.join(ROOT, "assets", "icon.jpg"), quality=92)

bg = Image.new("RGBA", im.size, BG + (255,))
bg.alpha_composite(im)
px = list(bg.convert("RGB").getdata())
runs = []
i = 0
while i < len(px):
    j = i
    while j + 1 < len(px) and px[j + 1] == px[i] and j + 1 - i < 255:
        j += 1
    runs.append((j - i + 1,) + px[i])
    i = j + 1

out = os.path.join(ROOT, "src", "logo.h")
with open(out, "w") as f:
    f.write("/* Generated by tools/make_logo.py from the XBE's $$XTIMAGE. Do not edit. */\n")
    f.write(f"#define LOGO_W {SIZE}\n#define LOGO_H {SIZE}\n")
    f.write(f"#define LOGO_BG_R {BG[0]}\n#define LOGO_BG_G {BG[1]}\n#define LOGO_BG_B {BG[2]}\n")
    f.write("/* runs of (count, r, g, b), row-major from the top */\n")
    f.write(f"static const unsigned char k_logo_rle[{len(runs) * 4}] = {{\n")
    flat = [v for r in runs for v in r]
    for k in range(0, len(flat), 24):
        f.write("    " + ",".join(str(v) for v in flat[k:k + 24]) + ",\n")
    f.write("};\n")
print(f"{out}: {SIZE}x{SIZE}, {len(runs)} runs ({len(runs) * 4} bytes)", file=sys.stderr)
