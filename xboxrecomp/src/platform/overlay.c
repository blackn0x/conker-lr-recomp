void (*recomp_quit_hook)(void);

void recomp_host_quit(const char *why)
{
    static volatile int once;
    if (once++)
        return;
    fprintf(stderr, "[quit] %s\n", why);
    if (recomp_quit_hook)
        recomp_quit_hook();
    fflush(NULL);
#if defined(__SWITCH__)
    exit(0);
#else
    _exit(0);
#endif
}

