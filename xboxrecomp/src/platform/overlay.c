void ovl_begin(void)
{
    memset(s_back, 0, sizeof s_back);
}

void ovl_rect(int x, int y, int w, int h, uint32_t rgba)
{
    int i, j;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > OVL_W) w = OVL_W - x;
    if (y + h > OVL_H) h = OVL_H - y;
    for (j = 0; j < h; j++)
        for (i = 0; i < w; i++)
            s_back[(y + j) * OVL_W + x + i] = rgba;
}

int ovl_text_width(int scale, const char *s)
{
    int n = (int)strlen(s);
    return n ? (n * 6 - 1) * scale : 0;
}

void ovl_text(int x, int y, int scale, uint32_t rgba, const char *s)
{
    for (; *s; s++, x += 6 * scale) {
        int c = (unsigned char)*s, r, b;
        if (c >= 'a' && c <= 'z')
            c -= 32;
        if (c < 32 || c > 95)
            c = '?';
        for (r = 0; r < 7; r++)
            for (b = 0; b < 5; b++)
                if (k_font[c - 32][r] & (0x10 >> b))
                    ovl_rect(x + b * scale, y + r * scale, scale, scale, rgba);
    }
}

void ovl_publish(int visible)
{
    pthread_mutex_lock(&s_lock);
    if (visible)
        memcpy(s_front, s_back, sizeof s_front);
    s_visible = visible;
    s_gen++;
    pthread_mutex_unlock(&s_lock);
}

int ovl_take(unsigned *gen, void *dst)
{
    int r;
    pthread_mutex_lock(&s_lock);
    r = s_visible;
    if (r && *gen != s_gen) {
        memcpy(dst, s_front, sizeof s_front);
        *gen = s_gen;
        r = 2;
    }
    pthread_mutex_unlock(&s_lock);
    return r;
}
